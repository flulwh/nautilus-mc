#!/usr/bin/env python3
"""Regenerate ``frontend/src/generated/contract.ts`` from backend constants.

The frontend must not hand-copy roles / objects / actions: when ``authz.py``
gains or drops one, re-run this script and commit the result.
``tests/test_contract.py`` fails CI if the checked-in file drifts.

Usage:  python scripts/gen_contract.py [--check]
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "frontend" / "src" / "generated" / "contract.ts"

os.environ.setdefault("NAUTILUS_DATA_DIR", str(ROOT / ".tmp" / "gen-contract"))
sys.path.insert(0, str(ROOT))

from nautilus.authz import ACTIONS, OBJECTS, ROLES  # noqa: E402

HEADER = """\
// GENERATED by scripts/gen_contract.py from nautilus/authz.py -- do not edit by hand.
// Re-run `python scripts/gen_contract.py` after changing roles, objects or actions.
"""


def render() -> str:
    def block(name: str, items: list[str], type_name: str) -> str:
        arr = ", ".join(json.dumps(i) for i in items)
        return f"export const {name} = [{arr}] as const;\nexport type {type_name} = (typeof {name})[number];"

    return "\n".join(
        [
            HEADER,
            block("ROLES", ROLES, "Role"),
            block("OBJECTS", OBJECTS, "PermObject"),
            block("ACTIONS", ACTIONS, "PermAction"),
            "",
        ]
    )


def main() -> int:
    content = render()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != content:
            print(f"stale: {TARGET} differs, run python scripts/gen_contract.py", file=sys.stderr)
            return 1
        print("contract.ts is up to date")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
